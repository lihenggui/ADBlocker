//! Name pairs derived from AdguardTeam/Scriptlets at
//! 420ffa66c6e713ffa95c80e4bfa356b1a796c3a3, wiki/compatibility-table.md and
//! src/scriptlets/*Names, resolved against the bundled uBlock Origin resources.
//! Trusted counterparts also use the references in the bundled uBlock source.

use super::Unsupported;

pub(super) fn resolve(name: &str) -> Result<&'static str, Unsupported> {
    NAMES
        .binary_search_by_key(&name, |(name, _)| *name)
        .map(|index| NAMES[index].1)
        .map_err(|_| {
            if UNBUNDLED.binary_search(&name).is_ok() {
                Unsupported::ScriptletResource
            } else {
                Unsupported::ScriptletName
            }
        })
}

