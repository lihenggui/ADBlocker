//! What was asked for cannot be: a name that is not one, a command or
//! arguments nobody knows. Told apart from what went wrong in the doing,
//! for whoever asked to be told so.

#[derive(Debug)]
pub struct Malformed(pub String);

impl std::fmt::Display for Malformed {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for Malformed {}
