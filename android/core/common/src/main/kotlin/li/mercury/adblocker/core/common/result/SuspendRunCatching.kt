package li.mercury.adblocker.core.common.result

import kotlinx.coroutines.CancellationException

/**
 * [runCatching] for suspending work. A coroutine that is cancelled must end,
 * so its [CancellationException] is thrown on rather than kept in the
 * result, where the work after it would carry on as if nothing happened.
 */
suspend inline fun <T> suspendRunCatching(crossinline block: suspend () -> T): Result<T> = try {
    Result.success(block())
} catch (e: CancellationException) {
    throw e
} catch (e: Exception) {
    Result.failure(e)
}
